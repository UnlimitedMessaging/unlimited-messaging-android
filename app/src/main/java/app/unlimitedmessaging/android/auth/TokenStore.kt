package app.unlimitedmessaging.android.auth

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import android.util.Log
import androidx.core.content.edit
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Everything needed to call the API as the signed-in user, and to refresh or revoke that access. */
@Serializable
data class Session(
    val accessToken: String,
    /** Null when the server did not issue one: the session then ends when the access token does. */
    val refreshToken: String?,
    val tokenEndpoint: String,
    val revocationEndpoint: String?,
)

/**
 * Persists the [Session], encrypted with an AES-256-GCM key held by the
 * Android Keystore.
 *
 * The key never leaves the Keystore (hardware-backed on most devices), so the
 * stored ciphertext is useless if copied off the phone. Backups are disabled
 * for the same reason (see data_extraction_rules.xml).
 *
 * This replaces androidx.security:security-crypto, deprecated in 2025, with
 * the few lines it actually took.
 */
class TokenStore(context: Context) {
    private val prefs = context.getSharedPreferences("session", Context.MODE_PRIVATE)
    private val json = Json { ignoreUnknownKeys = true }

    @Volatile
    private var cached: Session? = load()

    /** The current session, or null when signed out. */
    val session: Session? get() = cached

    @Synchronized
    fun save(session: Session) {
        val plaintext = json.encodeToString(Session.serializer(), session)
        prefs.edit(commit = true) { putString(KEY_SESSION, encrypt(plaintext)) }
        cached = session
    }

    @Synchronized
    fun clear() {
        prefs.edit(commit = true) { remove(KEY_SESSION) }
        cached = null
    }

    private fun load(): Session? {
        val stored = prefs.getString(KEY_SESSION, null) ?: return null
        return try {
            json.decodeFromString(Session.serializer(), decrypt(stored))
        } catch (e: Exception) {
            // Key gone (e.g. app data partially restored) or corrupt entry:
            // the only way forward is signing in again.
            Log.w(TAG, "Stored session unreadable, discarding it", e)
            prefs.edit(commit = true) { remove(KEY_SESSION) }
            null
        }
    }

    private fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey())
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        // Stored as IV || ciphertext+tag. The IV is generated by the Keystore
        // for every encryption, never reused.
        return Base64.encodeToString(cipher.iv + ciphertext, Base64.NO_WRAP)
    }

    private fun decrypt(stored: String): String {
        val bytes = Base64.decode(stored, Base64.NO_WRAP)
        val iv = bytes.copyOfRange(0, IV_LENGTH)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey(), GCMParameterSpec(TAG_LENGTH_BITS, iv))
        return String(cipher.doFinal(bytes, IV_LENGTH, bytes.size - IV_LENGTH), Charsets.UTF_8)
    }

    private fun secretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(KEYSTORE).apply { load(null) }
        (keyStore.getKey(KEY_ALIAS, null) as SecretKey?)?.let { return it }
        return KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE).run {
            init(
                KeyGenParameterSpec.Builder(
                    KEY_ALIAS,
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                )
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    .setKeySize(256)
                    .build(),
            )
            generateKey()
        }
    }

    private companion object {
        const val TAG = "TokenStore"
        const val KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "session-key"
        const val KEY_SESSION = "session"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val IV_LENGTH = 12
        const val TAG_LENGTH_BITS = 128
    }
}
